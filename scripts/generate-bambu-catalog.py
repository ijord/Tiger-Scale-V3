#!/usr/bin/env python3
"""Build the scale's compact, non-refill Bambu SKU index from Studio's catalog.

Usage: python scripts/generate-bambu-catalog.py path/to/id_catalog.json
Source: https://github.com/TigerTag-Project/TigerTag-Studio-Manager/blob/main/assets/db/tigertag/id_catalog.json
Product details are fetched and validated at import time, not frozen here.
"""
import hashlib
import json
from pathlib import Path
import re
import sys


def generate(source):
    entries = {}
    for item in json.loads(source):
        fields = item.get('RFID_Data') or {}
        sku = (item.get('sku') or '').upper()
        if fields.get('id_brand') != 35123 or item.get('info1') is not False:
            continue
        if fields.get('id_type') != 142 or not re.fullmatch(r'[A-Z0-9]+-[A-Z0-9]+-1\.75-[0-9]+-SPL', sku):
            continue
        entries.setdefault(sku, []).append(item)
    rows = []
    for sku, items in sorted(entries.items()):
        # A duplicate SKU is not a deterministic product identity.
        if len(items) != 1:
            continue
        item = items[0]
        fields = item['RFID_Data']
        rows.append(f'    {{"{sku}", {int(item["id"])}u, {int(fields["id_material"])}, '
                    f'{int(fields.get("id_aspect1") or 104)}, {int(fields.get("id_aspect2") or 255)}}},')
    if not rows:
        raise ValueError('No unambiguous Bambu products found')
    return ('// Generated by scripts/generate-bambu-catalog.py; do not edit.\n'
            '// Source: TigerTag-Project/TigerTag-Studio-Manager assets/db/tigertag/id_catalog.json\n'
            f'// Source SHA256: {hashlib.sha256(source).hexdigest()}\n'
            '#pragma once\n#include <stdint.h>\n\n'
            'struct BambuCatalogEntry { const char* sku; uint32_t product; uint16_t material; uint8_t aspect1, aspect2; };\n'
            'static const BambuCatalogEntry BAMBU_CATALOG[] = {\n' + '\n'.join(rows) + '\n};\n')


if __name__ == '__main__':
    output = Path(__file__).resolve().parents[1] / 'TigerTagSplashESP32/bambu_catalog.h'
    output.write_text(generate(Path(sys.argv[1]).read_bytes()), encoding='utf-8', newline='\n')
    print(f'Generated {output.name}')
